import Foundation

/// An arbitrary JSON value.
///
/// Used for exactly one thing: holding a method response's arguments between
/// parsing the envelope and knowing what type to decode them as.
///
/// `methodResponses` is a list of heterogeneous `[name, arguments, callId]`
/// triples, so the arguments cannot be decoded until the name has been read
/// and matched against the call that produced it — and `Decoder` gives no way
/// to keep a container around for later. Capturing the arguments here and
/// re-decoding them per call is the cost of that. It is bounded: the server
/// caps a response at 500 objects and 32 calls.
///
/// Integers are kept distinct from doubles so a re-encode round trip does not
/// turn `50` into `50.0` — which would be invisible until some property was
/// decoded as `Int`.
public enum JSONValue: Hashable, Sendable {
    case null
    case bool(Bool)
    case int(Int)
    case double(Double)
    case string(String)
    case array([JSONValue])
    case object([String: JSONValue])
}

extension JSONValue: Codable {
    public init(from decoder: any Decoder) throws {
        let container = try decoder.singleValueContainer()

        if container.decodeNil() {
            self = .null
        } else if let value = try? container.decode(Bool.self) {
            self = .bool(value)
        } else if let value = try? container.decode(Int.self) {
            self = .int(value)
        } else if let value = try? container.decode(Double.self) {
            self = .double(value)
        } else if let value = try? container.decode(String.self) {
            self = .string(value)
        } else if let value = try? container.decode([JSONValue].self) {
            self = .array(value)
        } else if let value = try? container.decode([String: JSONValue].self) {
            self = .object(value)
        } else {
            throw DecodingError.dataCorruptedError(
                in: container,
                debugDescription: "Unrepresentable JSON value"
            )
        }
    }

    public func encode(to encoder: any Encoder) throws {
        var container = encoder.singleValueContainer()

        switch self {
        case .null: try container.encodeNil()
        case .bool(let value): try container.encode(value)
        case .int(let value): try container.encode(value)
        case .double(let value): try container.encode(value)
        case .string(let value): try container.encode(value)
        case .array(let value): try container.encode(value)
        case .object(let value): try container.encode(value)
        }
    }
}

extension JSONValue {
    public var objectValue: [String: JSONValue]? {
        guard case .object(let value) = self else { return nil }
        return value
    }

    public var stringValue: String? {
        guard case .string(let value) = self else { return nil }
        return value
    }

    public var arrayValue: [JSONValue]? {
        guard case .array(let value) = self else { return nil }
        return value
    }

    /// Re-decodes this value as `T`.
    ///
    /// - Note: Goes through `Data`. See the type's own documentation for why
    ///   the round trip exists at all.
    public func decode<T: Decodable>(as type: T.Type = T.self) throws -> T {
        let data = try JSONEncoder().encode(self)
        return try JSONDecoder().decode(T.self, from: data)
    }
}
